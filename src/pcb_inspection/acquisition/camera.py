"""Live camera access for camera-first acquisition (phone as a webcam through DroidCam).

* list_video_devices(): the video devices Windows reports, by name, in the
  DirectShow order that OpenCV's CAP_DSHOW backend uses for its indices. The
  index to use comes from the capture config (camera.index); it is never
  hard-coded and another camera is never substituted for it.
* OpenCVCamera: one device, cv2.VideoCapture(index, cv2.CAP_DSHOW), opened with a
  requested resolution / FPS. What the device actually delivers is read back
  from the frames, never assumed. Open failures give a clear message.
* FrameGrabber: reads frames on a background thread, keeps the newest one and
  reports the stream state (live / connecting / disconnected / frozen). It
  re-opens the device by itself after a disconnect. Only its thread reads and
  releases the camera.
* check_camera(): open -> read frames -> release diagnostic (scripts/check_camera.py).
* CameraLock: ONE program at a time per camera. Two programs reading the same DroidCam stream compete for the
  CPU and the driver (lag, frozen windows, failed captures). OpenCVCamera.open() takes a machine-wide lock for
  its device; another program gets "camera N is in use by <program> (pid, since ...)" and keeps retrying.
  The operating system releases the lock when the owning program ends, even after a crash.

A frozen stream (no pixel changes for a few seconds) is treated like a
disconnect: a phone-as-webcam driver may keep delivering its last or a
placeholder frame after the phone is gone, and such a frame must never be
saved as a capture.
"""

