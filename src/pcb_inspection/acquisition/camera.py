@dataclass(frozen=True)
class VideoDevice:
    index: int          # index for cv2.VideoCapture(index, CAP_DSHOW)
    name: str


@dataclass(frozen=True)
class Frame:
    image: np.ndarray   # BGR, as delivered by OpenCV
    seq: int            # running number of frames received by the grabber
    t: float            # monotonic arrival time
    wall_time: datetime # local wall-clock arrival time (capture timestamp)
    signature: str      # hash of a pixel sample; equal signatures = unchanged picture


class CameraSource(Protocol):
    name: str

    def open(self) -> bool: ...
    def read(self) -> np.ndarray | None: ...
    def release(self) -> bool | None: ...
    def properties(self) -> dict[str, float | None]: ...


def frame_signature(image: np.ndarray) -> str:
    """Cheap fingerprint of a frame (every 8th pixel). Sensor noise changes it on a live stream."""
    return hashlib.blake2b(np.ascontiguousarray(image[::8, ::8]).tobytes(), digest_size=16).hexdigest()


def is_blank(image: np.ndarray) -> bool:
    """True if every sampled pixel has the same value. A real camera picture always varies (even a dark
    one has sensor noise); a uniform frame is generated by a disabled / covered camera's driver."""
    sample = image[::4, ::4]
    return sample.size == 0 or int(sample.max()) == int(sample.min())


# --- device enumeration ---------------------------------------------------------

def list_video_devices(names_provider: Callable[[], list[str]] | None = None,
                       probe: Callable[[int], bool] | None = None, max_probe: int = 6) -> list[VideoDevice]:
    """Video devices by name (DirectShow order). Falls back to probing indices if names are unavailable."""
    names = (names_provider or directshow_device_names)()
    if names:
        return [VideoDevice(i, name) for i, name in enumerate(names)]
    probe = probe or _probe_index
    return [VideoDevice(i, f"Camera {i}") for i in range(max_probe) if probe(i)]


def device_at(devices: list[VideoDevice], index: int) -> VideoDevice | None:
    """The device with the configured index, or None. Never substitutes another camera."""
    return next((d for d in devices if d.index == index), None)


def _probe_index(index: int) -> bool:
    import cv2
    cap = cv2.VideoCapture(index, cv2.CAP_DSHOW if sys.platform == "win32" else cv2.CAP_ANY)
    try:
        return bool(cap.isOpened())
    finally:
        cap.release()


def directshow_device_names() -> list[str]:
    """FriendlyName of every DirectShow video input device, in enumeration order; [] if unavailable."""
    if sys.platform != "win32":
        return []
    try:
        return _directshow_names()
    except (OSError, AttributeError, ValueError):
        return []


def _directshow_names() -> list[str]:
    import ctypes
    from ctypes import POINTER, byref, c_long, c_ulong, c_ushort, c_void_p, c_wchar_p

    class GUID(ctypes.Structure):
        _fields_ = [("d1", c_ulong), ("d2", c_ushort), ("d3", c_ushort), ("d4", ctypes.c_ubyte * 8)]

    class VARIANT(ctypes.Structure):
        _fields_ = [("vt", c_ushort), ("r1", c_ushort), ("r2", c_ushort), ("r3", c_ushort),
                    ("value", c_void_p), ("extra", c_void_p)]

    ole32, oleaut32 = ctypes.windll.ole32, ctypes.windll.oleaut32
    ole32.CoInitializeEx.restype = ole32.CoCreateInstance.restype = c_long

    def guid(text: str) -> GUID:
        g = GUID()
        if ole32.CLSIDFromString(c_wchar_p(text), byref(g)) != 0:
            raise OSError(f"bad GUID {text}")
        return g

    def call(obj: c_void_p, index: int, argtypes: list, *args) -> int:
        vtable = ctypes.cast(obj, POINTER(POINTER(c_void_p))).contents
        return ctypes.WINFUNCTYPE(c_long, c_void_p, *argtypes)(vtable[index])(obj, *args)

    def release(obj: c_void_p) -> None:
        if obj:
            ctypes.WINFUNCTYPE(c_ulong, c_void_p)(ctypes.cast(obj, POINTER(POINTER(c_void_p))).contents[2])(obj)

    hr = ole32.CoInitializeEx(None, 0x2)  # apartment-threaded; S_FALSE / RPC_E_CHANGED_MODE: COM already up
    names: list[str] = []
    dev_enum, enum_mon = c_void_p(), c_void_p()
    try:
        if ole32.CoCreateInstance(byref(guid("{62BE5D10-60EB-11d0-BD3B-00A0C911CE86}")), None, 1,
                                  byref(guid("{29840822-5B84-11D0-BD3B-00A0C911CE86}")), byref(dev_enum)) != 0:
            raise OSError("system device enumerator unavailable")
        video_category = guid("{860BB310-5D01-11d0-BD3B-00A0C911CE86}")
        if call(dev_enum, 3, [POINTER(GUID), POINTER(c_void_p), c_ulong], byref(video_category), byref(enum_mon), 0) != 0:
            return []  # S_FALSE: no video devices
        iid_property_bag = guid("{55272A00-42CB-11CE-8135-00AA004BB851}")
        while True:
            moniker, fetched = c_void_p(), c_ulong()
            if call(enum_mon, 3, [c_ulong, POINTER(c_void_p), POINTER(c_ulong)], 1, byref(moniker), byref(fetched)) != 0 \
                    or not fetched.value:
                break
            name, bag = "", c_void_p()
            if call(moniker, 9, [c_void_p, c_void_p, POINTER(GUID), POINTER(c_void_p)],
                    None, None, byref(iid_property_bag), byref(bag)) == 0:
                value = VARIANT()
                if call(bag, 3, [c_wchar_p, POINTER(VARIANT), c_void_p], "FriendlyName", byref(value), None) == 0 \
                        and value.vt == 8 and value.value:  # VT_BSTR
                    name = ctypes.wstring_at(value.value)
                oleaut32.VariantClear(byref(value))
                release(bag)
            release(moniker)
            names.append(name or f"Camera {len(names)}")
    finally:
        release(enum_mon)
        release(dev_enum)
        if hr in (0, 1):
            ole32.CoUninitialize()
    return names


