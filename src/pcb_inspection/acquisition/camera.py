BACKENDS = ("dshow", "msmf", "any")


class CameraBusyError(RuntimeError):
    """The camera is held by another program."""


def _lock_dir() -> Path:
    return Path(os.environ.get("PCB_CAMERA_LOCK_DIR") or tempfile.gettempdir())


class CameraLock:
    """Machine-wide, per-device lock held while a program has the camera open.

    An OS file lock (msvcrt on Windows, fcntl elsewhere): released by the operating system when the process ends,
    so a crashed program never leaves the camera locked. Within one process the lock is shared (reference
    counted): it protects programs from each other, not objects of one program from each other.
    """

    _held: dict[str, tuple[object, int]] = {}         # key -> (open file, reference count) in THIS process
    _guard = threading.Lock()

    def __init__(self, backend: str, index: int):
        self.key = f"{backend}_{index}"
        self.index = index
        self.path = _lock_dir() / f"pcb_inspection_camera_{self.key}.lock"
        self.info_path = self.path.with_suffix(".owner.json")
        self.held = False

    def acquire(self) -> None:
        if self.held:
            return
        with CameraLock._guard:
            if self.key in CameraLock._held:
                f, n = CameraLock._held[self.key]
                CameraLock._held[self.key] = (f, n + 1)
                self.held = True
                return
            self.path.parent.mkdir(parents=True, exist_ok=True)
            f = open(self.path, "a+b")
            try:
                _lock_file(f)
            except OSError:
                f.close()
                raise CameraBusyError(self._busy_message()) from None
            try:
                program = " ".join([Path(sys.argv[0]).name, *sys.argv[1:]]) if sys.argv and sys.argv[0] else "python"
                self.info_path.write_text(json.dumps({"pid": os.getpid(), "program": program,
                                                      "since": datetime.now().isoformat(timespec="seconds")}),
                                          encoding="utf-8")
            except OSError:
                pass
            CameraLock._held[self.key] = (f, 1)
            self.held = True

    def release(self) -> None:
        if not self.held:
            return
        self.held = False
        with CameraLock._guard:
            f, n = CameraLock._held.get(self.key, (None, 0))
            if f is None:
                return
            if n > 1:
                CameraLock._held[self.key] = (f, n - 1)
                return
            del CameraLock._held[self.key]
            try:
                _unlock_file(f)
            finally:
                f.close()

    def _busy_message(self) -> str:
        try:
            owner = json.loads(self.info_path.read_text(encoding="utf-8"))
            since = str(owner.get("since", "?")).replace("T", " ")
            who = f"{owner.get('program')} (pid {owner.get('pid')}, since {since})"
        except (OSError, ValueError):
            who = "another program"
        return (f"camera {self.index} is in use by {who}. Only one program can use the camera at a time: close the "
                "other program (station, acquisition, live inspection, web app live camera); this one keeps retrying.")


def _lock_file(f) -> None:
    if sys.platform == "win32":
        import msvcrt
        f.seek(0)
        msvcrt.locking(f.fileno(), msvcrt.LK_NBLCK, 1)
    else:
        import fcntl
        fcntl.flock(f.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)


def _unlock_file(f) -> None:
    try:
        if sys.platform == "win32":
            import msvcrt
            f.seek(0)
            msvcrt.locking(f.fileno(), msvcrt.LK_UNLCK, 1)
        else:
            import fcntl
            fcntl.flock(f.fileno(), fcntl.LOCK_UN)
    except OSError:
        pass


def _backend_id(backend: str) -> int:
    import cv2
    if backend not in BACKENDS:
        raise ValueError(f"camera backend must be one of {BACKENDS}, got {backend!r}")
    if sys.platform != "win32":
        return cv2.CAP_ANY
    return {"dshow": cv2.CAP_DSHOW, "msmf": cv2.CAP_MSMF, "any": cv2.CAP_ANY}[backend]


class OpenCVCamera:
    """A video device opened through OpenCV: cv2.VideoCapture(index, cv2.CAP_DSHOW) on Windows, so that the
    index matches list_video_devices(). Opened at most once at a time; open() releases any earlier handle."""

    def __init__(self, index: int, name: str, width: int | None = None, height: int | None = None,
                 fps: float | None = None, backend: str = "dshow"):
        if not isinstance(index, int) or isinstance(index, bool) or index < 0:
            raise ValueError(f"camera index must be an integer >= 0, got {index!r}")
        self.index, self.name, self.backend = index, name, backend
        self.requested = (width, height, fps)
        self.last_error = ""
        self._cap = None
        self._lock = CameraLock(backend, index)

    def open(self) -> bool:
        """Open the device. False (with last_error set) if OpenCV cannot open it or another program has it."""
        import cv2
        self.release()
        self.last_error = ""
        try:
            self._lock.acquire()
        except CameraBusyError as e:
            self.last_error = str(e)
            return False
        try:
            cap = cv2.VideoCapture(self.index, _backend_id(self.backend))
        except cv2.error as e:
            self._lock.release()
            self.last_error = self._open_error(f"OpenCV error: {e}")
            return False
        if not cap.isOpened():
            cap.release()
            self._lock.release()
            self.last_error = self._open_error("cap.isOpened() is False")
            return False
        width, height, fps = self.requested
        if width and height:
            cap.set(cv2.CAP_PROP_FRAME_WIDTH, width)
            cap.set(cv2.CAP_PROP_FRAME_HEIGHT, height)
        if fps:
            cap.set(cv2.CAP_PROP_FPS, fps)
        self._cap = cap
        return True

    def _open_error(self, detail: str) -> str:
        if "droidcam" in self.name.lower():
            hint = "Start the DroidCam client on the PC, connect the phone and press Start, then Reconnect."
        else:
            hint = ("Check the index with 'python scripts/check_camera.py --list' and close any other "
                    "application using the camera (Camera app, Teams, browser).")
        return f"Cannot open camera {self.index} ('{self.name}') with backend {self.backend.upper()} ({detail}). {hint}"

    @property
    def is_open(self) -> bool:
        return self._cap is not None and bool(self._cap.isOpened())

    def read(self) -> np.ndarray | None:
        """One frame (BGR), or None if cap.read() fails or returns an empty frame."""
        if self._cap is None:
            return None
        import cv2
        try:
            ok, frame = self._cap.read()
        except cv2.error:
            return None
        return frame if ok and frame is not None and frame.size else None

    def release(self) -> bool:
        """Release the device. True if it is closed afterwards (or was not open)."""
        cap, self._cap = self._cap, None
        if cap is None:
            self._lock.release()
            return True
        cap.release()
        self._lock.release()
        return not cap.isOpened()

    def properties(self) -> dict[str, float | None]:
        """What the driver reports; the delivered frame size is authoritative (FrameGrabber.info)."""
        if self._cap is None:
            return {}
        import cv2
        fps = self._cap.get(cv2.CAP_PROP_FPS)
        return {"fps_reported": float(fps) if fps and fps > 0 else None}


# --- background frame reader -----------------------------------------------------

class FrameGrabber:
    """Keeps the newest frame of a camera and the stream state; re-opens the camera after a disconnect."""

    def __init__(self, camera: CameraSource, *, failures_before_disconnect: int = 15, frozen_after_s: float | None = 3.0,
                 reconnect_every_s: float = 2.0, blank_after_s: float = 1.0, clock: Callable[[], float] = time.monotonic,
                 now: Callable[[], datetime] = datetime.now):
        self.camera = camera
        self.failures_before_disconnect = failures_before_disconnect
        self.frozen_after_s = frozen_after_s
        self.blank_after_s = blank_after_s      # webcams may send a few blank frames while starting
        self._blank_since: float | None = None
        self.reconnect_every_s = reconnect_every_s
        self._clock, self._now = clock, now
        self._lock = threading.Condition()
        self._thread: threading.Thread | None = None
        self._running = False
        self._opened = False
        self._next_open_at = 0.0
        self._failures = 0
        self._latest: Frame | None = None
        self._seq = 0
        self._last_change_t: float | None = None
        self._arrivals: list[float] = []
        self._reconnect_requested = False
        self._props: dict[str, float | None] = {}   # read once per open: OpenCV is not thread-safe
        self._frames_since_open = 0
        self.status = STATUS_CONNECTING
        self.message = ""

    # thread control
    def start(self) -> None:
        if self._thread is None:
            self._running = True
            self._thread = threading.Thread(target=self._run, name="frame-grabber", daemon=True)
            self._thread.start()

    def stop(self, timeout: float = 5.0) -> None:
        """Stop reading and release the camera.

        With a running thread, the thread itself releases the camera when it
        leaves its loop, so release() never runs while read() is in progress on
        another thread. If a driver read blocks longer than timeout, the thread
        still releases the camera as soon as that read returns.
        """
        self._running = False
        thread, self._thread = self._thread, None
        if thread is None:
            self.camera.release()
            self._opened = False
            return
        thread.join(timeout)

    def request_reconnect(self) -> None:
        """Close and re-open the device on the next step (operator pressed Reconnect)."""
        self._reconnect_requested = True

    def _run(self) -> None:
        try:
            while self._running:
                try:
                    got_frame = self.step()
                except Exception as e:  # never let the reader thread die silently with a stale "live" state
                    self._close(f"Camera error: {e}. Retrying...", STATUS_DISCONNECTED)
                    self._next_open_at = self._clock() + self.reconnect_every_s
                    got_frame = False
                if not got_frame:
                    time.sleep(0.05)
        finally:
            self.camera.release()     # the reading thread is the only one that releases the camera
            self._opened = False

    # one iteration; called by the thread, or directly by tests
    def step(self) -> bool:
        """Open / read once. Returns True if a frame was received."""
        now = self._clock()
        if self._reconnect_requested:
            self._reconnect_requested = False
            self._close("reconnecting...", STATUS_CONNECTING)
            self._next_open_at = now
        if not self._opened:
            if now < self._next_open_at:
                return False
            if self.camera.open():
                self._opened, self._failures, self._last_change_t = True, 0, None
                self._frames_since_open, self._blank_since = 0, None
                self._props = self.camera.properties()
                self._set(STATUS_CONNECTING, "camera opened, waiting for frames")
            else:
                self._next_open_at = now + self.reconnect_every_s
                error = getattr(self.camera, "last_error", "") or f"Cannot open camera '{self.camera.name}'."
                self._set(STATUS_DISCONNECTED, f"{error} Retrying every {self.reconnect_every_s:g} s.")
                return False
        image = self.camera.read()
        now = self._clock()
        if image is None:
            self._failures += 1
            if self._failures >= self.failures_before_disconnect:
                if self._frames_since_open:
                    message = "Camera disconnected (cap.read() failed). Retrying..."
                else:
                    message = (f"Camera '{self.camera.name}' opened but cap.read() returned no frame. "
                               "Retrying...")
                self._close(message, STATUS_DISCONNECTED)
                self._next_open_at = now + self.reconnect_every_s
            return False
        self._failures = 0
        self._frames_since_open += 1
        signature = frame_signature(image)
        if not is_blank(image):
            self._blank_since = None
        elif self._blank_since is None:
            self._blank_since = now
        with self._lock:
            previous = self._latest
            if previous is None or signature != previous.signature or self._last_change_t is None:
                self._last_change_t = now
            self._seq += 1
            self._latest = Frame(image, self._seq, now, self._now(), signature)
            self._arrivals = [t for t in self._arrivals if now - t <= 2.0] + [now]
            if self._blank_since is not None and now - self._blank_since >= self.blank_after_s:
                self._set(STATUS_BLANK, BLANK_PICTURE_HINT)
            elif self._blank_since is not None:
                self._set(STATUS_CONNECTING, "waiting for a picture (camera starting)")
            elif self.frozen_after_s is not None and now - self._last_change_t >= self.frozen_after_s:
                self._set(STATUS_FROZEN, "Camera stream frozen (no new picture for "
                                         f"{self.frozen_after_s:g} s). Check the camera connection "
                                         "(cable / DroidCam client), then press Reconnect.")
            else:
                self._set(STATUS_LIVE, "")
            self._lock.notify_all()
        return True

    def _close(self, message: str, status: str) -> None:
        self.camera.release()
        self._opened = False
        self._set(status, message)

    def _set(self, status: str, message: str) -> None:
        self.status, self.message = status, message

    # readers
    @property
    def is_live(self) -> bool:
        return self.status == STATUS_LIVE

    def latest(self) -> Frame | None:
        with self._lock:
            return self._latest

    def wait_for_frame_after(self, t: float, timeout: float = 2.0) -> Frame | None:
        """The first frame that arrived after time t (a fresh frame, not one already on screen), or None."""
        deadline = self._clock() + timeout
        with self._lock:
            while True:
                if self._latest is not None and self._latest.t > t:
                    return self._latest
                remaining = deadline - self._clock()
                if remaining <= 0:
                    return None
                self._lock.wait(min(remaining, 0.05))

    def measured_fps(self) -> float | None:
        with self._lock:
            arrivals = list(self._arrivals)
        if len(arrivals) < 2 or arrivals[-1] == arrivals[0]:
            return None
        return (len(arrivals) - 1) / (arrivals[-1] - arrivals[0])

    def info(self) -> dict[str, object]:
        """Camera metadata for session / image records: name, delivered size, reported and measured FPS."""
        frame = self.latest()
        props = self._props
        fps = self.measured_fps()
        return {
            "name": self.camera.name,
            "index": getattr(self.camera, "index", None),
            "backend": getattr(self.camera, "backend", None),
            "width": int(frame.image.shape[1]) if frame is not None else None,
            "height": int(frame.image.shape[0]) if frame is not None else None,
            "fps_reported": props.get("fps_reported"),
            "fps_measured": round(fps, 1) if fps else None,
        }


@dataclass
class CameraCheck:
    """Result of check_camera()."""

    index: int
    name: str
    backend: str
    frames_requested: int
    opened: bool = False
    frames_read: int = 0
    blank_frames: int = 0
    width: int | None = None
    height: int | None = None
    channels: int | None = None
    fps_measured: float | None = None
    released: bool = False
    static: bool = False            # every non-blank frame identical: not a live picture
    error: str = ""

    @property
    def ok(self) -> bool:
        return self.opened and self.frames_read == self.frames_requested and self.released and not self.error


def check_camera(index: int, name: str = "", backend: str = "dshow", width: int | None = None,
                 height: int | None = None, fps: float | None = None, frames: int = 30,
                 camera_factory: Callable[..., OpenCVCamera] = OpenCVCamera, check_picture: bool = True) -> CameraCheck:
    """Diagnostic: open the camera exactly as the application does, read frames, release it.

    Checks cap.isOpened(), the return value of every cap.read(), the frame size,
    that the frames show a picture (not a uniform blank frame from a covered /
    disabled camera) and that the device reports closed after release(). The
    camera is released in every case.
    """
    camera = camera_factory(index, name or f"camera {index}", width, height, fps, backend=backend)
    result = CameraCheck(index, camera.name, backend, frames)
    try:
        if not camera.open():
            result.error = camera.last_error
            return result
        result.opened = True
        start = time.perf_counter()
        trailing_blank = 0
        signatures: set[str] = set()
        for i in range(frames):
            image = camera.read()
            if image is None:
                result.error = f"camera {index} opened, but cap.read() returned no frame (frame {i + 1} of {frames})"
                break
            result.frames_read += 1
            blank = is_blank(image)
            result.blank_frames += blank
            trailing_blank = trailing_blank + 1 if blank else 0
            if not blank:
                signatures.add(frame_signature(image))
            result.height, result.width = int(image.shape[0]), int(image.shape[1])
            result.channels = int(image.shape[2]) if image.ndim == 3 else 1
        elapsed = time.perf_counter() - start
        if result.frames_read > 1 and elapsed > 0:
            result.fps_measured = round(result.frames_read / elapsed, 1)
        # blank frames while the camera starts are normal; a picture that is still blank at the end is not
        if check_picture and result.frames_read and trailing_blank >= min(5, result.frames_read) and not result.error:
            result.error = (f"camera {index}: the last {trailing_blank} of {result.frames_read} frames are blank. "
                            f"{BLANK_PICTURE_HINT}")
        # a live sensor always changes a little; a picture that never changes is a static screen or a frozen stream
        non_blank = result.frames_read - result.blank_frames
        result.static = non_blank >= STATIC_MIN_FRAMES and len(signatures) == 1
        if check_picture and result.static and not result.error:
            result.error = f"camera {index}: the picture did not change in {non_blank} frames. {STATIC_PICTURE_HINT}"
    finally:
        result.released = bool(camera.release())
        if not result.released and not result.error:
            result.error = f"camera {index} still reports open after release()"
    return result


def encode_png(image: np.ndarray) -> bytes:
    """Lossless PNG bytes of a BGR frame (cv2.imencode avoids imwrite's non-ASCII path problem on Windows)."""
    import cv2
    ok, buffer = cv2.imencode(".png", image, [cv2.IMWRITE_PNG_COMPRESSION, 3])
    if not ok:
        raise OSError("PNG encoding failed")
    return buffer.tobytes()
